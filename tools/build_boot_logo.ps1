# Rebuild the two small, antialiased alpha layers from the editable SVG.
# Uses Windows System.Drawing only; no image converter or runtime SVG dependency.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
[xml]$svg = Get-Content -LiteralPath (Join-Path $root 'assets/boot_logo.svg') -Raw
$width = 396; $height = 90; $supersample = 4
$output = [System.Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by tools/build_boot_logo.ps1 from assets/boot_logo.svg.')
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <cstdint>')
[void]$output.AppendLine('namespace sm::boot_asset {')
[void]$output.AppendLine("inline constexpr int width=$width, height=$height;")
foreach ($layer in @('white','accent')) {
    $large = [System.Drawing.Bitmap]::new($width*$supersample,$height*$supersample)
    $g = [System.Drawing.Graphics]::FromImage($large)
    $g.Clear([System.Drawing.Color]::Transparent)
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.ScaleTransform([single]($width*$supersample/1100),[single]($height*$supersample/250))
    foreach ($group in $svg.svg.g) {
        $isAccent = $group.id.StartsWith('accent')
        if (($layer -eq 'accent') -ne $isAccent) { continue }
        foreach ($element in $group.ChildNodes) {
            if ($element.Name -eq 'circle') {
                $r=[single]$element.r
                $g.FillEllipse([System.Drawing.Brushes]::White,([single]$element.cx-$r),([single]$element.cy-$r),2*$r,2*$r)
                continue
            }
            if ($element.Name -ne 'path') { continue }
            $path = [System.Drawing.Drawing2D.GraphicsPath]::new([System.Drawing.Drawing2D.FillMode]::Alternate)
            $tokens = [regex]::Matches($element.d,'[MLCQZ]|-?\d+(?:\.\d+)?')
            $i=0; [single]$x=0; [single]$y=0
            while ($i -lt $tokens.Count) {
                $command=$tokens[$i++].Value
                if ($command -eq 'Z') { $path.CloseFigure(); continue }
                $count = switch($command) { 'M' {2} 'L' {2} 'C' {6} 'Q' {4} default { throw "Unsupported SVG command $command" } }
                $v=@(); for($j=0;$j -lt $count;$j++) { $v += [single]::Parse($tokens[$i++].Value,[Globalization.CultureInfo]::InvariantCulture) }
                switch ($command) {
                    'M' { $path.StartFigure(); $x=$v[0]; $y=$v[1] }
                    'L' { $path.AddLine($x,$y,$v[0],$v[1]); $x=$v[0]; $y=$v[1] }
                    'C' { $path.AddBezier($x,$y,$v[0],$v[1],$v[2],$v[3],$v[4],$v[5]); $x=$v[4]; $y=$v[5] }
                    'Q' { $path.AddBezier($x,$y,($x+2*($v[0]-$x)/3),($y+2*($v[1]-$y)/3),($v[2]+2*($v[0]-$v[2])/3),($v[3]+2*($v[1]-$v[3])/3),$v[2],$v[3]); $x=$v[2]; $y=$v[3] }
                }
            }
            if ($group.fill -ne 'none') { $g.FillPath([System.Drawing.Brushes]::White,$path) }
            else {
                $pen = [System.Drawing.Pen]::new([System.Drawing.Color]::White,[single]$group.'stroke-width')
                $pen.StartCap=$pen.EndCap=[System.Drawing.Drawing2D.LineCap]::Round
                $pen.LineJoin=[System.Drawing.Drawing2D.LineJoin]::Round
                $g.DrawPath($pen,$path); $pen.Dispose()
            }
            $path.Dispose()
        }
    }
    $g.Dispose()
    $runs = [System.Collections.Generic.List[uint16]]::new()
    $previous=-1; $length=0
    for($y=0;$y -lt $height;$y++) { for($x=0;$x -lt $width;$x++) {
        $sum=0
        for($sy=0;$sy -lt $supersample;$sy++) { for($sx=0;$sx -lt $supersample;$sx++) {
            $sum += $large.GetPixel($x*$supersample+$sx,$y*$supersample+$sy).A
        } }
        $alpha=[int][Math]::Round($sum/($supersample*$supersample))
        if($alpha -eq $previous -and $length -lt 255) { $length++ }
        else { if($length) { $runs.Add([uint16](($previous -shl 8) -bor $length)) }; $previous=$alpha; $length=1 }
    } }
    if($length) { $runs.Add([uint16](($previous -shl 8) -bor $length)) }
    $large.Dispose()
    [void]$output.AppendLine("inline constexpr uint16_t ${layer}[] = {")
    for($i=0;$i -lt $runs.Count;$i+=20) {
        $end=[Math]::Min($i+19,$runs.Count-1)
        [void]$output.AppendLine('  '+(($runs[$i..$end] | ForEach-Object { '0x{0:x4}' -f $_ }) -join ',')+',')
    }
    [void]$output.AppendLine('};')
    Write-Output "$layer layer: $($runs.Count*2) bytes RLE"
}
[void]$output.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $root 'ui/boot_logo_asset.hpp'),$output.ToString(),[Text.UTF8Encoding]::new($false))
