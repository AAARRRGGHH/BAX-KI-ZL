"""Draw the companion's code-defined icons as antialiased alpha masks."""
from pathlib import Path
import math
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.tools/launcher-python'))
from PIL import Image, ImageDraw, ImageFont
sys.path.insert(0,str(ROOT/'launcher'))
from brand import ACCENT

SIZE, SS = 128, 4


def main():
    masks = {}

    def canvas(name):
        image = Image.new('L', (SIZE*SS, SIZE*SS))
        masks[name] = image
        return image

    def stroke(image, points, width=5):
        drawing = ImageDraw.Draw(image)
        p = [(round(x*SS), round(y*SS)) for x, y in points]
        drawing.line(p, fill=255, width=width*SS, joint='curve')
        r = width*SS/2
        for x, y in (p[0], p[-1]):
            drawing.ellipse((round(x-r), round(y-r), round(x+r), round(y+r)), fill=255)

    def path(image, start, commands, width=5):
        points, current = [start], start
        for command in commands:
            if len(command) == 2:
                points.append(command)
                current = command
            else:
                x0, y0 = current
                x1, y1, x2, y2, x3, y3 = command
                for i in range(1, 33):
                    t, s = i/32, 1-i/32
                    points.append((s**3*x0+3*s*s*t*x1+3*s*t*t*x2+t**3*x3,
                                   s**3*y0+3*s*s*t*y1+3*s*t*t*y2+t**3*y3))
                current = (x3, y3)
        stroke(image, points, width)

    hand = canvas('hand_white')
    path(hand, (48, 115), [(48, 101), (32, 91, 29, 74, 23, 60),
         (19, 50, 28, 45, 35, 51), (43, 64), (43, 40),
         (43, 30, 57, 30, 57, 40), (57, 65), (57, 25),
         (57, 15, 72, 15, 72, 25), (72, 65), (72, 55),
         (72, 45, 86, 45, 86, 55), (86, 71), (86, 68),
         (86, 58, 100, 58, 100, 68), (100, 89),
         (100, 97, 96, 104, 96, 115), (48, 115)], 5)
    tap = canvas('hand_accent')
    path(tap, (30, 33), [(26, 20, 33, 10, 44, 10), (54, -1, 80, 2, 82, 25)], 5)

    reset_text = canvas('reset_white')
    drawing = ImageDraw.Draw(reset_text)
    font = ImageFont.truetype(str(ROOT / 'assets/fonts/Barlow-Regular.ttf'), 24*SS)
    drawing.text((64*SS, 63*SS), 'RESET', font=font, fill=255, anchor='mm')
    reset = canvas('reset_accent')
    stroke(reset, [(64+51*math.cos(math.radians(a)), 64+51*math.sin(math.radians(a)))
                   for a in range(40, 316)], 8)
    ImageDraw.Draw(reset).polygon([(118*SS, 44*SS), (85*SS, 44*SS), (118*SS, 11*SS)], fill=255)

    back = canvas('return_white')
    path(back, (54, 24), [(79, 24), (120, 24, 120, 89, 79, 89), (20, 89)], 8)
    stroke(back, [(43, 66), (20, 89), (43, 112)], 8)
    canvas('return_accent')

    lines = ['// Generated by tools/build_companion_icons.py. Do not edit.', '#pragma once',
             '#include <cstdint>', 'namespace companion::art {', 'inline constexpr int size=128;']
    preview = Image.new('RGB', (SIZE*3, SIZE), 'black')
    for index, (name, large) in enumerate(masks.items()):
        image = large.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
        preview.paste(ACCENT if name.endswith('accent') else 'white', ((index//2)*SIZE, 0), image)
        runs = []
        previous, count = -1, 0
        for alpha in image.tobytes():
            if alpha == previous and count < 255:
                count += 1
            else:
                if count:
                    runs.append((previous << 8) | count)
                previous, count = alpha, 1
        runs.append((previous << 8) | count)
        lines.append(f'inline constexpr uint16_t {name}[] = {{')
        for offset in range(0, len(runs), 20):
            lines.append(' '+','.join(f'0x{r:04x}' for r in runs[offset:offset+20])+',')
        lines.append('};')
    lines.append('}')
    (ROOT / 'platform/desktop/companion_icon_assets.hpp').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    output = ROOT / 'build/companion'
    output.mkdir(parents=True, exist_ok=True)
    preview.save(output / 'icons-preview.png')


if __name__ == '__main__':
    main()
